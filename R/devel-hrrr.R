process_hrrr <- function(
  date = c("2021-05-04", "2021-05-04"),
  variable = NULL,
  path = NULL,
  extent = NULL,
  daily_agg = FALSE,
  fun = "mean",
  ...
) {
  # ----------------------------------------------------------------------------
  # Check common arguments.
  # ----------------------------------------------------------------------------
  # Check source-specific arguments.
  # ----------------------------------------------------------------------------
  # Coerce `date` to vector of 2 if not already.
  date <- fl_dates(sequence_dates(date, hyphen = TRUE))
  # ----------------------------------------------------------------------------
  # Identify time-relevant HRRR file paths in `path`.
  chr_datapaths <- resolve_paths(
    date = date,
    path = path,
    pattern = paste0(
      "^hrrr\\.[0-9]{8}\\.t[0-9]{2}z\\.wrf",
      "(prs|nat|sfc|subh)f[0-9]{2}\\.grib2$"
    ),
    hyphen = FALSE
  )
  # ----------------------------------------------------------------------------
  # Import, clean, and stack hourly files; return raster.
  stack_hourly(
    paths = chr_datapaths,
    extent = extent,
    variable = variable,
    short = "T2M"
  )
}

################################################################################
stack_hourly <- function(
  paths,
  extent,
  variable,
  short
) {
  # ----------------------------------------------------------------------------
  # Variable-specific raster layers as a list.
  list_rast <- lapply(
    # --------------------------------------------------------------------------
    # Execute for each path.
    paths,
    function(x) {
      # ------------------------------------------------------------------------
      # Import full raster data from path (e.g. .nc, .nc4, .grib, etc).
      rast_x <- terra::rast(x, win = extent)
      # ------------------------------------------------------------------------
      # Identify variable-specific layers.
      idx_var <- grep(
        tolower(variable),
        tolower(names(rast_x)),
        fixed = TRUE
      )
      # ------------------------------------------------------------------------
      # Subset full raster data to variable-specific, single time. layer
      terra::subset(rast_x, idx_var)
    }
  )
  # ----------------------------------------------------------------------------
  # Merge turn multi-time, single-varaible list of raster layers.
  rast_variable <- terra::rast(list_rast)
  # ----------------------------------------------------------------------------
  # Clean `terra` time stamp.
  terra::time(rast_variable) <- as.POSIXct(terra::time(rast_variable))
  # ----------------------------------------------------------------------------
  # Apply variable short name and time stamp to layer names.
  names(rast_variable) <- paste0(
    short,
    "_",
    format(terra::time(rast_variable), "%Y%m%d_%H%M")
  )
  # ----------------------------------------------------------------------------
  rast_variable
}

