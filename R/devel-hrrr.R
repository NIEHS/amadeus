#' Discover source paths by filename pattern and date range
#'
#' @description
#' Search immediate entries in input directories for names matching a regular
#' expression, then retain paths containing a date in the requested range.
#'
#' @param date character(1) or character(2). A single date or inclusive range
#'   endpoints in `"YYYY-MM-DD"` format. Endpoints may be supplied in either
#'   order. Dates must be between `"1950-01-01"` and [base::Sys.Date()],
#'   inclusive.
#' @param input character. Directory path or paths to search.
#'   Passed to [base::list.files()] without normalization or existence checks.
#' @param pattern character(1). Regular expression used by [base::list.files()]
#'   to select file or directory names. Matching is case-sensitive.
#' @param hyphen logical(1). Non-missing flag controlling whether generated
#'   date strings include hyphens when matching paths. Defaults to `TRUE`,
#'   matching dates such as `"2024-01-01"`. Use `FALSE` to match `"20240101"`.
#'
#' @details
#' The date sequence is generated by [amadeus::sequence_dates()], which
#' validates `date` and `hyphen`, orders range endpoints, and includes every
#' day in the range. A single date selects one day. Invalid dates or dates
#' outside the permitted range raise an error.
#'
#' Dates are combined into a regular expression and matched against the full
#' returned paths, including directory names. Matching uses date text rather
#' than file contents, file modification times, or parsed source metadata.
#'
#' Subdirectories are not searched, but directory paths can be returned when
#' their names match `pattern` and their paths contain a requested date.
#' Hidden entries are excluded according to [base::list.files()] defaults.
#' Repeated path strings are removed, preserving the order returned by that
#' function. No additional argument validation is performed beyond that
#' delegated to [amadeus::sequence_dates()] and [base::list.files()].
#'
#' @return
#' A character vector of unique matching paths, or `character(0)` when
#' no entries match. Paths include their input directory prefix but are not
#' normalized to absolute paths.
#'
#' @importFrom amadeus sequence_dates
#' @seealso [sedona_geos()], [amadeus::sequence_dates()],
#'   [base::list.files()]
#' @keywords internal
#' @examples
#' \dontrun{
#' geos_files <- discover(
#'   date = c("2024-01-01", "2024-01-02"),
#'   input = "data/geos",
#'   pattern = "^GEOS-CF",
#'   hyphen = FALSE
#' )
#' }
#' @export
resolve_paths <- function(
  date,
  path,
  pattern,
  hyphen = TRUE
) {
  # ----------------------------------------------------------------------------
  # Identify file paths from all files in the path.
  chr_paths <- list.files(
    path,
    pattern = pattern,
    full.names = TRUE,
    recursive = FALSE
  )
  # ----------------------------------------------------------------------------
  # Generate sequence from user supplied dates.
  chr_datesofinterest <- sequence_dates(date = date, hyphen = hyphen)
  # ----------------------------------------------------------------------------
  # Select only those file paths which align with user supplied date sequence.
  unique(
    grep(
      paste(
        chr_datesofinterest,
        collapse = "|"
      ),
      chr_paths,
      value = TRUE
    )
  )
}
