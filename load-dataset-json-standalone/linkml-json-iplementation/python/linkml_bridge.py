"""LinkML compilation and strict validation for the R catalog converter.

No catalog JSON is generated by Python. The R converter owns serialization.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import importlib.metadata
import json
from pathlib import Path
import sys

from jsonschema import Draft201909Validator, FormatChecker
from linkml.generators.jsonschemagen import JsonSchemaGenerator

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "dataset_spec_objects"))
import catalog_workflow as catalog  # noqa: E402

SCHEMA = catalog.SCHEMA
IMPLEMENTATION = ROOT / "linkml-json-iplementation"


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n")


def read_json(path):
    def reject_duplicates(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"Duplicate JSON key: {key}")
            result[key] = value
        return result

    def reject_constant(value):
        raise ValueError(f"Non-finite JSON number: {value}")

    return json.loads(Path(path).read_text(), object_pairs_hook=reject_duplicates,
                      parse_constant=reject_constant)


def semantic_equal(left, right):
    """Compare JSON structure; distinguish booleans from numbers, 1 equals 1.0."""
    if isinstance(left, bool) or isinstance(right, bool):
        return type(left) is type(right) and left == right
    if isinstance(left, dict) and isinstance(right, dict):
        return left.keys() == right.keys() and all(semantic_equal(left[k], right[k]) for k in left)
    if isinstance(left, list) and isinstance(right, list):
        return len(left) == len(right) and all(semantic_equal(a, b) for a, b in zip(left, right))
    if isinstance(left, (int, float)) and isinstance(right, (int, float)):
        return left == right
    return type(left) is type(right) and left == right


def validator_for(schema):
    Draft201909Validator.check_schema(schema)
    return Draft201909Validator(schema, format_checker=FormatChecker())


def schema_errors(validator, document, name):
    return [{"document": name, "path": "/" + "/".join(str(x) for x in e.absolute_path),
             "message": e.message, "check": "json_schema"}
            for e in validator.iter_errors(document)]


def schema_slots(schema_source=SCHEMA):
    slots = {}
    for path in sorted(Path(schema_source).parent.glob("*.yaml")):
        slots.update(catalog.load(path).get("slots", {}))
    return slots


def check_document(document, validator, slots, name):
    errors = schema_errors(validator, document, name)
    if not errors:
        try:
            # Nullable optional references/collections are valid JSON Schema.
            # Normalize only the reference-checking view, never the output.
            reference_view = {
                collection: [{k: v for k, v in record.items() if v is not None}
                             for record in (document.get(collection) or [])]
                for collection in catalog.COLLECTIONS
            }
            catalog.check_references(reference_view, slots)
        except (ValueError, KeyError, TypeError) as exc:
            errors.append({"document": name, "path": "/", "check": "references",
                           "message": str(exc)})
    return errors


def load_sources(input_dir):
    bundles = catalog.load_bundles(input_dir)
    global_document = catalog.load(input_dir / "global_catalog.yaml")
    united = catalog.assemble(bundles)
    if not semantic_equal(global_document, united):
        raise ValueError("Source global YAML differs from the deduplicated family union; regenerate it with catalog_workflow.py before conversion")
    documents = {**bundles, "global_catalog": global_document}
    for name, document in documents.items():
        if set(document) - {"schema_version", *catalog.COLLECTIONS}:
            raise ValueError(f"{name}: this converter targets the existing catalog-only collections")
        # Reject non-JSON source objects and non-finite numeric values.
        json.dumps(document, allow_nan=False)
    return documents


def package_versions():
    return {p: importlib.metadata.version(p)
            for p in ("linkml", "linkml-runtime", "jsonschema", "PyYAML")}


def safe_output(output):
    protected = [ROOT / "global_dataset_catalogs", ROOT / "validated_catalog_handles",
                 ROOT / "amadeus_schema"]
    if output == ROOT or any(output == p or output.is_relative_to(p) for p in protected):
        raise ValueError("Use a separate output directory; input catalog/schema trees are protected")


def compile_schema(schema_source=SCHEMA):
    """Compile the LinkML model once; shared by batch and dataset loaders."""
    schema_source = Path(schema_source)
    if not schema_source.is_file():
        raise ValueError(f"LinkML schema does not exist: {schema_source}")
    catalog.load(schema_source)  # Reject duplicate keys before LinkML loading.
    schema = json.loads(JsonSchemaGenerator(str(schema_source)).serialize())
    validator_for(schema)
    return schema


def prepare(input_dir, output):
    schema = compile_schema()
    validator = validator_for(schema)
    documents = load_sources(input_dir)
    slots = schema_slots()
    errors = [e for name, doc in documents.items()
              for e in check_document(doc, validator, slots, name)]
    if errors:
        raise ValueError(json.dumps(errors, ensure_ascii=False))
    output.mkdir(parents=True, exist_ok=True)
    schema_path = output / "amadeus_schema.schema.json"
    write_json(schema_path, schema)
    sources = [{"name": name, "input": str(input_dir / f"{name}.yaml"),
                "output": str(output / "catalogs" / f"{name}.json"),
                "sha256": sha256(input_dir / f"{name}.yaml")}
               for name in sorted(documents)]
    implementation_files = [
        IMPLEMENTATION / "run_pipeline.R", IMPLEMENTATION / "R/convert_catalog.R",
        Path(__file__), IMPLEMENTATION / "requirements.txt",
        ROOT / "dataset_spec_objects/catalog_workflow.py",
        ROOT / "dataset_spec_objects/catalog_updates_20261109/read_catalog.R",
        ROOT / "dataset_spec_objects/catalog_requirements.txt",
        ROOT / "validated_catalog_handles/validate_catalogs.py",
    ]
    dependencies = sorted(SCHEMA.parent.glob("*.yaml")) + implementation_files
    plan = {"target_class": "AmadeusDatabase", "schema_source": str(SCHEMA),
            "schema_file": str(schema_path), "schema_sha256": sha256(schema_path),
            "input_directory": str(input_dir), "output_directory": str(output),
            "documents": sources,
            "dependency_sha256": {str(p): sha256(p) for p in dependencies},
            "python_version": sys.version, "python_packages": package_versions()}
    write_json(output / "conversion_plan.json", plan)
    write_json(output / "validation_report.json", {
        "status": "NOT_RUN", "phase": "source_validated_conversion_pending",
        "source_documents_checked": len(documents), "output_documents_checked": 0,
        "message": "Source YAML passed; no converted JSON is accepted until final validation passes."})
    print(f"PREPARED: {len(documents)} valid YAML documents; exported {schema_path}")
    return plan


def verify_plan(plan):
    checks = {**plan["dependency_sha256"], plan["schema_file"]: plan["schema_sha256"]}
    checks.update({d["input"]: d["sha256"] for d in plan["documents"]})
    for path, digest in checks.items():
        if not Path(path).is_file() or sha256(path) != digest:
            raise ValueError(f"Input/schema/implementation changed after prepare: {path}; rerun the pipeline")
    if package_versions() != plan["python_packages"]:
        raise ValueError("Python package versions changed after prepare")


def validate_outputs(output):
    plan = read_json(output / "conversion_plan.json")
    verify_plan(plan)
    schema = read_json(plan["schema_file"])
    validator = validator_for(schema)
    slots = schema_slots()
    expected = {Path(d["output"]).name for d in plan["documents"]}
    actual = {p.name for p in (output / "catalogs").glob("*.json")}
    if actual != expected:
        raise ValueError(f"Output document membership differs from plan: missing={sorted(expected-actual)}, extra={sorted(actual-expected)}")
    errors = []
    converted = {}
    checks = []
    for d in plan["documents"]:
        name = d["name"]
        document = read_json(d["output"])
        converted[name] = document
        local_errors = check_document(document, validator, slots, name)
        if not semantic_equal(catalog.load(d["input"]), document):
            local_errors.append({"document": name, "path": "/", "check": "source_json_parity",
                                 "message": "Converted JSON differs from source YAML values, field presence, order or structure"})
        errors.extend(local_errors)
        checks.append({"document": name, "json_schema": "FAIL" if any(e["check"] == "json_schema" for e in local_errors) else "PASS",
                       "references_and_parity": "FAIL" if local_errors else "PASS"})
    if not errors:
        united = catalog.assemble({n: b for n, b in converted.items() if n != "global_catalog"})
        if not semantic_equal(united, converted["global_catalog"]):
            errors.append({"check": "global_union", "document": "global_catalog", "path": "/",
                           "message": "Converted global JSON is not the family union"})
    report = {"status": "FAIL" if errors else "PASS", "phase": "output_validation",
              "validated_utc": datetime.now(timezone.utc).isoformat(),
              "schema_file": plan["schema_file"], "schema_sha256": plan["schema_sha256"],
              "schema_source": plan["schema_source"], "target_class": plan["target_class"],
              "source_documents_checked": len(plan["documents"]),
              "output_documents_checked": len(converted), "documents": checks,
              "checks": {"schema": "FAIL" if any(e["check"] == "json_schema" for e in errors) else "PASS",
                         "source_parity_and_relationships": "FAIL" if errors else "PASS",
                         "input_hashes": "PASS", "scientific_provider_evidence": "NOT_RUN",
                         "rds_and_discovery_handles": "NOT_RUN"},
              "global_counts": {c: len(converted["global_catalog"].get(c, [])) for c in catalog.COLLECTIONS},
              "errors": errors,
              "scope": "Catalog structure, source parity and six-collection relationships. Not scientific correctness, native-array validation or R adapter certification."}
    write_json(output / "validation_report.json", report)
    if errors:
        return False
    r_summary = read_json(output / "r_conversion_report.json")
    manifest = {"schema_sha256": plan["schema_sha256"], "dependency_sha256": plan["dependency_sha256"],
                "input_sha256": {d["input"]: d["sha256"] for d in plan["documents"]},
                "output_sha256": {str(Path(d["output"]).relative_to(output)): sha256(d["output"]) for d in plan["documents"]},
                "validation_report_sha256": sha256(output / "validation_report.json"),
                "python_version": plan["python_version"], "python_packages": plan["python_packages"],
                "r_conversion": r_summary}
    write_json(output / "manifest.json", manifest)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["prepare", "validate"])
    parser.add_argument("--input-dir", type=Path, default=ROOT / "global_dataset_catalogs")
    parser.add_argument("--output-dir", type=Path, default=IMPLEMENTATION / "output")
    args = parser.parse_args()
    output = args.output_dir.resolve()
    try:
        safe_output(output)
        if args.command == "prepare":
            prepare(args.input_dir.resolve(), output)
            return 0
        if not validate_outputs(output):
            print(f"FAIL: see {output / 'validation_report.json'}", file=sys.stderr)
            return 1
        print(f"PASS: validated converted catalogs using {output / 'amadeus_schema.schema.json'}")
        return 0
    except Exception as exc:
        # Only a designated build folder receives failure diagnostics.
        try:
            safe_output(output)
            write_json(output / "validation_report.json", {"status": "FAIL", "phase": args.command,
                       "error": str(exc), "scientific_provider_evidence": "NOT_RUN"})
        except Exception:
            pass
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
